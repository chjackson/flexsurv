test_that("background hazards retain the correct delayed-entry score", {
    old <- options(flexsurv.test.analytic.derivatives=TRUE)
    on.exit(options(old))
    start <- rep(5,10)
    stop <- rep(7,10)
    fit <- flexsurvreg(Surv(start,stop,rep(1,10))~1, dist="exp", bhazard=rep(.1,10))
    expect_equal(unname(fit$res["rate","est"]), .4, tolerance=1e-4)
    expect_equal(fit$loglik, 10*(log(.5)-.4*2), tolerance=1e-7)
    expect_lt(fit$deriv.test$error, 1e-5)
    expect_lt(fit$hess.test$error, 1e-5)
})
